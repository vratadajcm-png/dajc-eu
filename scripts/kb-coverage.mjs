#!/usr/bin/env node
// DAJC AI Legal Coverage: 50 jurisdictions x legal sub-areas x official sources
// x stored documents (src/lib/kb/coverage.mjs). Internal report, never a public
// page: writes JSON, a Markdown summary and a self-contained HTML dashboard.
//
//   DAJC_KB_COVERAGE_DB_URL=... node scripts/kb-coverage.mjs [--out-dir reports/legal-coverage] [--date YYYY-MM-DD]
//   node scripts/kb-coverage.mjs --inventory inventory.json      (rows of dajc_kb.library_inventory, e.g. exported)
//   node scripts/kb-coverage.mjs                                  (plan only: nothing stored)
//
// Any library role can read the text-free view dajc_kb.library_inventory.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { buildCoverage, COVERAGE_STATUSES } from '../src/lib/kb/coverage.mjs';
import { maskInGitHubActions, redact } from '../src/lib/kb/db-guard.mjs';

const args = process.argv.slice(2);
const value = (name) => (args.includes(name) ? args[args.indexOf(name) + 1] : null);
const outDir = value('--out-dir') || 'reports/legal-coverage';
const onDate = value('--date') || new Date().toISOString().slice(0, 10);
const read = (p) => JSON.parse(readFileSync(p, 'utf8'));
const manifest = read('config/legal-library/manifest.json');
const sourceChecks = read('config/legal-library/source-checks.json');
const audits = read('config/legal-library/coverage-evidence.json').entries;

let inventory = [];
let inventorySource = 'none (plan only)';
if (value('--inventory')) {
  inventory = read(value('--inventory'));
  inventorySource = `file ${value('--inventory')}`;
} else if (process.env.DAJC_KB_COVERAGE_DB_URL) {
  const url = process.env.DAJC_KB_COVERAGE_DB_URL;
  maskInGitHubActions(url);
  const { default: postgres } = await import('postgres');
  const sql = postgres(url, { max: 1, prepare: false, onnotice: () => undefined });
  try {
    inventory = await sql`select * from dajc_kb.library_inventory`;
    inventorySource = 'database (dajc_kb.library_inventory)';
  } catch (error) {
    console.error(`FAILED   ${redact(error?.message || error, url).slice(0, 300)}`);
    process.exit(1);
  } finally {
    await sql.end();
  }
}

const report = buildCoverage({ manifest, inventory, sourceChecks, audits, onDate });
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'coverage.json'), `${JSON.stringify({ inventorySource, sourceChecksOn: sourceChecks.checkedOn, ...report }, null, 1)}\n`);

const esc = (s) => String(s ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
const pct = (n) => `${((100 * n) / report.cellCount).toFixed(1)} %`;

// --- Markdown summary --------------------------------------------------------
const md = [];
md.push('# DAJC AI Legal Coverage', '');
md.push(`Generated by \`scripts/kb-coverage.mjs\` on ${onDate}; inventory: ${inventorySource}; source checks of ${sourceChecks.checkedOn} (${sourceChecks.environment}). Internal, not public.`, '');
md.push(`**${report.jurisdictionCount} jurisdictions × ${report.areaCount} legal sub-areas = ${report.cellCount} cells.** No jurisdiction is complete (${report.completeJurisdictions.length}/${report.jurisdictionCount}); completeness needs every cell COVERED or NOT_APPLICABLE through an audit with official evidence.`, '');
md.push('| Status | Cells | Share |', '|---|---|---|');
for (const s of COVERAGE_STATUSES) md.push(`| ${s} | ${report.totals[s]} | ${pct(report.totals[s])} |`);
md.push('', `Library: ${report.library.documents} of ${report.library.plannedDocuments} planned documents stored, ${report.library.versions} versions, ${report.library.verifiedVersions} AI- or person-verified, ${report.library.conflictedVersions} conflicted.`, '');
md.push('| Jurisdiction | PARTIAL | CONFLICTED | NOT_APPLICABLE | SOURCE_UNAVAILABLE | NOT_YET_RESEARCHED | COVERED | Stored documents | Official sources (access from the check environment) |', '|---|---|---|---|---|---|---|---|---|');
for (const j of report.jurisdictions) {
  const access = j.sources.map((s) => `${s.region ? `${s.region}: ` : ''}${s.domains[0]} ${s.access.join('/')}`).join('; ');
  md.push(`| ${j.code} ${esc(j.name)}${j.corridorOnly ? ' (corridor only)' : ''} | ${j.counts.PARTIAL} | ${j.counts.CONFLICTED} | ${j.counts.NOT_APPLICABLE} | ${j.counts.SOURCE_UNAVAILABLE} | ${j.counts.NOT_YET_RESEARCHED} | ${j.counts.COVERED} | ${j.documents} | ${access || 'none registered'} |`);
}
md.push('', 'PARTIAL never means complete: each such cell lists why (transposition of a directive, EEA incorporation, missing national implementing rules and sanctions, missing verification, regional legislation).');
writeFileSync(join(outDir, 'coverage.md'), `${md.join('\n')}\n`);

// --- HTML dashboard ----------------------------------------------------------
const color = { COVERED: '#1b7f3b', PARTIAL: '#d39b18', CONFLICTED: '#b3261e', NOT_APPLICABLE: '#7a7a7a', SOURCE_UNAVAILABLE: '#6a3fb5', NOT_YET_RESEARCHED: '#d9dde3' };
const groups = Object.entries(report.groups);
const head = groups.map(([g, l]) => `<th colspan="${report.areas.filter((a) => a.id.startsWith(`${g}.`)).length}" title="${esc(l.en)}">${g}</th>`).join('');
const sub = report.areas.map((a) => `<th class="v" title="${esc(`${a.id} - ${a.en}`)}">${esc(a.id.split('.')[1].replace(/_/g, ' '))}</th>`).join('');
const rows = report.jurisdictions.map((j) => {
  const cells = j.cells.map((c) => {
    const tip = [`${j.code} ${c.area}: ${c.status}`, c.documents.length ? `documents: ${c.documents.join(', ')}` : '', c.versions ? `${c.versions} versions, ${c.verifiedVersions} verified` : '', ...c.reasons, c.plannedNotImported.length ? `planned: ${c.plannedNotImported.join(', ')}` : ''].filter(Boolean).join('\n');
    return `<td class="c" style="background:${color[c.status]}" title="${esc(tip)}"></td>`;
  }).join('');
  return `<tr><th class="j" title="${esc(j.sources.map((s) => `${s.id}: ${s.access.join('/')} (reuse ${s.reuse})`).join('\n'))}">${j.code}${j.corridorOnly ? '*' : ''}</th>${cells}<td class="n">${j.counts.PARTIAL}</td><td class="n">${j.documents}</td></tr>`;
}).join('\n');
const legend = COVERAGE_STATUSES.map((s) => `<span class="l"><i style="background:${color[s]}"></i>${s} ${report.totals[s]}</span>`).join('');
writeFileSync(join(outDir, 'coverage.html'), `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="robots" content="noindex,nofollow">
<title>DAJC AI Legal Coverage</title><style>
:root{--bg:#fff;--fg:#1d2430;--muted:#5b6574;--line:#e5e8ec}@media (prefers-color-scheme:dark){:root{--bg:#12161c;--fg:#e8ecf1;--muted:#a0a9b5;--line:#2a313b}}
body{margin:0;padding:16px;background:var(--bg);color:var(--fg);font:14px/1.45 system-ui,-apple-system,Segoe UI,sans-serif}h1{font-size:20px;margin:0 0 4px}p{color:var(--muted);margin:4px 0 12px;max-width:80ch}
.wrap{overflow-x:auto;border:1px solid var(--line);border-radius:8px}table{border-collapse:collapse}th,td{border:1px solid var(--line)}th{font-weight:600;font-size:12px;padding:2px 4px}
th.v{writing-mode:vertical-rl;transform:rotate(180deg);height:150px;font-weight:400;color:var(--muted);white-space:nowrap}th.j{position:sticky;left:0;background:var(--bg);text-align:left;padding:2px 8px}
td.c{width:14px;height:18px;padding:0}td.n{font-variant-numeric:tabular-nums;text-align:right;padding:0 6px;color:var(--muted)}.l{display:inline-flex;align-items:center;gap:6px;margin:0 14px 8px 0;font-size:13px}.l i{width:12px;height:12px;border-radius:2px;display:inline-block}
</style></head><body><h1>DAJC AI Legal Coverage</h1>
<p>Internal, generated ${esc(onDate)} from ${esc(inventorySource)}. ${report.jurisdictionCount} jurisdictions × ${report.areaCount} legal sub-areas. ${report.completeJurisdictions.length} of ${report.jurisdictionCount} jurisdictions complete. Library: ${report.library.documents} documents, ${report.library.versions} versions, ${report.library.verifiedVersions} verified. * corridor scope only (${esc(report.corridorScope)}). Hover a cell for documents and reasons.</p>
<div>${legend}</div><div class="wrap"><table><thead><tr><th class="j"></th>${head}<th>partial</th><th>docs</th></tr><tr><th class="j">Code</th>${sub}<th></th><th></th></tr></thead><tbody>
${rows}
</tbody></table></div></body></html>
`);
console.log(`${report.jurisdictionCount} jurisdictions x ${report.areaCount} sub-areas; ${COVERAGE_STATUSES.map((s) => `${s} ${report.totals[s]}`).join(', ')}; complete ${report.completeJurisdictions.length} -> ${outDir}`);
