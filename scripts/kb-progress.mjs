#!/usr/bin/env node
// Renders config/legal-library/api-progress.json into
// docs/DAJC_AI_API_IMPLEMENTATION_PROGRESS.md (all 50 jurisdictions of
// config/europe-coverage.mjs, in development order). Fails if one is missing.
import { readFileSync, writeFileSync } from 'node:fs';
import { dajcEuropeCoverage } from '../config/europe-coverage.mjs';

const { jurisdictions } = JSON.parse(readFileSync('config/legal-library/api-progress.json', 'utf8'));
const missing = dajcEuropeCoverage.map(([c]) => c).filter((c) => !jurisdictions.some((j) => j.jurisdiction === c));
if (missing.length || jurisdictions.length !== 50) { console.error(`progress register incomplete: ${missing.join(', ') || 'wrong count'}`); process.exit(1); }
const sum = (k) => jurisdictions.reduce((s, j) => s + j[k], 0);
const lines = [
  '# DAJC AI - API-by-API legal acquisition: progress register', '',
  '> Generated by `scripts/kb-progress.mjs` from `config/legal-library/api-progress.json`. Resume from this register: continue with the first jurisdiction whose implementation is not complete. No automatic session resumption is configured.', '',
  `Imported documents (Neon dev): **${sum('importedDocuments')}** - AI verified versions: **${sum('aiVerifiedVersions')}** - jurisdictions: ${jurisdictions.length}`, '',
  '| # | Code | Jurisdiction | Provider (candidate) | Official API documentation | Implementation | Testing | Imported | AI verified | Known issues | Next |', '|---|---|---|---|---|---|---|---|---|---|---|',
  ...jurisdictions.map((j) => `| ${j.order} | ${j.jurisdiction} | ${j.name} | ${j.provider ?? '-'} | ${j.officialDocumentation ? `${j.officialDocumentation} (verified ${j.documentationVerifiedOn})` : 'not yet studied'} | ${j.implementation} | ${j.testing} | ${j.importedDocuments} | ${j.aiVerifiedVersions} | ${j.knownIssues.join(' ') || '-'} | ${j.next} |`), '',
];
writeFileSync('docs/DAJC_AI_API_IMPLEMENTATION_PROGRESS.md', `${lines.join('\n')}\n`);
console.log(`written for ${jurisdictions.length} jurisdictions`);
