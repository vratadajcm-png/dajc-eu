import { describe, expect, it } from 'vitest';
import { dictionary, t, uiLang, uiLangFromRequest, UI_KEYS, UI_LANGUAGES } from '../i18n';

describe('translatable interface strings (EN default, CS)', () => {
  it('every language has every key, non-empty, with the same placeholders', () => {
    for (const lang of UI_LANGUAGES) {
      const dict = dictionary(lang);
      for (const key of UI_KEYS) {
        expect(dict[key], `${lang}.${key}`).toBeTruthy();
        const placeholders = (text: string) => [...text.matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort();
        expect(placeholders(dict[key]), `${lang}.${key}`).toEqual(placeholders(dictionary('en')[key]));
      }
    }
  });

  it('carries the required visible AI label and levels', () => {
    expect(t('cs', 'aiNotice')).toBe('Odpověď vytvořila AI na základě ověřených zdrojů.');
    expect(t('en', 'aiNotice')).toBe('This answer was generated by AI based on verified sources.');
    expect([t('cs', 'level.VERIFIED'), t('cs', 'level.PARTIAL'), t('cs', 'level.UNKNOWN')]).toEqual(['OVĚŘENO', 'ČÁSTEČNĚ', 'NEVÍM']);
    expect(t('cs', 'support')).toMatch(/nezakládá žádnou výhodu/);
  });

  it('defaults to English for any other interface language', () => {
    expect(uiLang('de')).toBe('en');
    expect(uiLang(undefined)).toBe('en');
    expect(uiLang('CS')).toBe('cs');
    expect(uiLangFromRequest(new URL('https://www.dajc.eu/intelligence/ask'), 'cs-CZ,cs;q=0.9')).toBe('cs');
    expect(uiLangFromRequest(new URL('https://www.dajc.eu/intelligence/ask?lang=en'), 'cs-CZ')).toBe('en');
    expect(t('en', 'remaining', { n: 2, limit: 3 })).toBe('Questions left today: 2 of 3.');
  });
});
