const DICTIONARIES: Record<UiLang, Record<UiKey, string>> = { en, cs };

export function uiLang(value: string | null | undefined): UiLang {
  const code = String(value || '').trim().toLowerCase().slice(0, 2);
  return (UI_LANGUAGES as readonly string[]).includes(code) ? (code as UiLang) : 'en';
}

/** Interface language from ?lang= first, then the first Accept-Language entry. */
export function uiLangFromRequest(url: URL, acceptLanguage: string | null): UiLang {
  const param = url.searchParams.get('lang');
  if (param) return uiLang(param);
  return uiLang(acceptLanguage?.split(',')[0]);
}

export function t(lang: UiLang, key: UiKey, vars: Record<string, string | number> = {}): string {
  const text = DICTIONARIES[lang]?.[key] ?? en[key];
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

export function dictionary(lang: UiLang): Record<UiKey, string> {
  return DICTIONARIES[lang];
}

